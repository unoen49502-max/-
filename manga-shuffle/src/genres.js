export const GENRE_LABELS = Object.fromEntries(GENRES.map((g) => [g.id, g.label]));
GENRE_LABELS[UNCLASSIFIED] = 'ジャンル不明';

const HALF_TO_FULL_ALNUM = (s) => s.replace(/[A-Za-z0-9]/g, (c) =>
  String.fromCharCode(c.charCodeAt(0) + 0xfee0));

function normalize(text) {
  const lowered = String(text || '').toLowerCase();
  // 全角/半角ゆれを吸収するため、両方の表記を連結した文字列を検索対象にする。
  return `${lowered}\n${HALF_TO_FULL_ALNUM(lowered)}`;
}

/**
 * タイトル・本文・タグからジャンルを推定する。
 * 一作品が複数ジャンルに属するのは普通なので、上位を配列で返す。
 * @returns {{genres:string[], scores:Record<string,number>}}
 */
export function classify({ title = '', summary = '', tags = [] } = {}, { max = 3 } = {}) {
  // タイトルとタグは本文より効くので重み付けして評価する。
  const fields = [
    { text: normalize(title), weight: 3 },
    { text: normalize(tags.join(' ')), weight: 3 },
    { text: normalize(summary), weight: 1 },
  ];

  const scores = {};
  for (const genre of GENRES) {
    let score = 0;
    for (const [word, weight] of genre.keywords) {
      if (!weight) continue;
      const needle = word.toLowerCase();
      for (const field of fields) {
        if (field.text.includes(needle)) score += weight * field.weight;
      }
    }
    if (score > 0) scores[genre.id] = score;
  }

  const ranked = Object.entries(scores)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, max)
    .map(([id]) => id);

  return { genres: ranked.length ? ranked : [UNCLASSIFIED], scores };
}

export function labelOf(genreId) {
  return GENRE_LABELS[genreId] || genreId;
}
