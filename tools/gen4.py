import json
def mir(halfrows):  # half = 8 chars (cols0-7); mirror to 15
    out=[]
    for h in halfrows:
        assert len(h)==8, f"half len {len(h)}: {h}"
        full=h+h[:7][::-1]
        assert len(full)==15
        out.append(full)
    return out
def chk(rows):
    assert len(rows)==15, f"rows {len(rows)}"
    for r in rows: assert len(r)==15, f"width {len(r)}: {r}"
    return rows

